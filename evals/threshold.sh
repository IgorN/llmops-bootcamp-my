#!/bin/sh
# поріг evals за правилом курсу (hw5). N-1 при N<=10, інакше 85% від N з округленням угору.
# Один скрипт на CI і локальний запуск, щоб поріг не розходився і не застарівав з новим кейсом.
n=$(grep -c . "${1:-evals/golden.jsonl}")
if [ "$n" -le 10 ]; then echo $((n - 1)); else echo $(((85 * n + 99) / 100)); fi
